import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { prepareStatic } from './prepare-static.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'work', 'publish');
if (path.dirname(output) !== path.join(root, 'work')) throw new Error('Invalid publish directory');
fs.rmSync(output, {recursive:true, force:true});
const result = spawnSync('dotnet', ['publish', 'BonjourMtl/BonjourMtl.csproj', '-f', 'net10.0-browserwasm', '-c', 'Release', '-o', output], { cwd: path.join(root, 'src'), stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
const built = path.join(output, 'wwwroot');
if (!fs.existsSync(path.join(built, 'index.html'))) throw new Error('Browser output is missing index.html');
const dist = path.join(root, 'dist');
if (path.dirname(dist) !== root) throw new Error('Invalid output directory');
fs.rmSync(dist, {recursive:true, force:true});
fs.cpSync(built, dist, {recursive:true});
prepareStatic(root);
console.log('Ready to host: dist/');
